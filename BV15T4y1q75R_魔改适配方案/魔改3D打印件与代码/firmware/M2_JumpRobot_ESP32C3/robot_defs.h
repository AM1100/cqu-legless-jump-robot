/*
 * robot_defs.h —— 机载端固件的【纯类型声明】头文件
 * ----------------------------------------------------------------------------
 * 为什么要单独拆一个头文件：
 *   Arduino IDE 会把函数原型自动插到"第一个 #include 之后、第一个函数之前"。
 *   如果枚举/结构体写在 .ino 里，自动原型会出现在它们**之前**，编译器就会报
 *   "MotorDir was not declared in this scope" 这种莫名其妙的错。
 *   把类型放进被 include 的头文件，自动原型就能看到全部类型。
 *   （这是 arduino-esp32 3.x 下的稳定写法，2.x 同样适用）
 * ============================================================================
 */
