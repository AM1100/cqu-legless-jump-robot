// ============================================================================
// 分段（"三次跳跃"工程路线，03 文档 §0.2）
// ----------------------------------------------------------------------------
//  ★ V2.1：第 2 段从"偏航舵机 + 微跳脉冲掉头"改为"双轮差速平地原地掉头"。
//    SEG_PIVOT 段 **不蓄能、不起跳、不占相位**：它就停在 S10_WAIT_CONFIRM 里，
//    由操作员用 wl/wr 在地面把车转 180°，转到位再按确认进第 3 段。
//    这样"跨板"动作仍然只有第 1 跳和第 3 跳两次真正的弹射。
