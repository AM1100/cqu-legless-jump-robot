enum SegKind : uint8_t {
  SEG_JUMP  = 0,   // 蓄能 → 弹射越板
  SEG_TURN  = 1,   // ⚠ 已停用（偏航舵机不装机）：原"偏航选向 + 微跳脉冲"
  SEG_PIVOT = 2,   // V2.1：地面差速原地掉头，不蓄能不起跳
};

struct Seg {
  const char* name;
  SegKind     kind;
  uint16_t    pitchDeg;   // 仅作参考，实际角度来自 Config
};

