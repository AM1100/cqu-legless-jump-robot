// 锁死方式：两种都是"零驱动"，区别只在电机绕组是开路还是短路
enum WheelLockMode : uint8_t {
  WL_HIZ          = 0,  // 高阻：两输入皆低，绕组开路，轮可被外力自由转动
  WL_BRAKE        = 1,  // 制动：两输入皆高，绕组短路，轮被电磁制动（默认，抗落地冲击）
};

