// ============================================================================
// 遥控指令字节（03 文档 §6.2）
// ============================================================================
enum Cmd : uint8_t {
  CMD_NONE      = 0x00,
  CMD_ARM       = 0x01,   // 预蓄能
  CMD_JUMP      = 0x02,   // 释放（仅 S3）
  CMD_PITCH     = 0x03,   // 单独调俯仰
  CMD_YAW       = 0x04,   // ⚠ V2.1 停用（偏航舵机不装机）；字节**不复用**，只回 [REJ]
  CMD_CONFIRM   = 0x05,   // ★人工确认（S10 唯一出口）
  CMD_DISARM    = 0x06,   // 反转泄能
  CMD_GOTO      = 0x08,   // 跳到第 N 段
  CMD_TURN_MORE = 0x09,   // ⚠ V2.1 停用（脉冲掉头随偏航舵机一起停用），字节不复用
  CMD_MACRO     = 0x10,   // "一键记住下一步"（≠ 自动连跳）
  CMD_STOP      = 0x20,   // 急停
  // ★ V2.0 新增：区域2 双螺旋轮差速调向（仅 S1_IDLE / S10_WAIT_CONFIRM 可进）
  CMD_WHEEL_PIVOT_L = 0x30, // 原地左转（逆时针）180°
  CMD_WHEEL_PIVOT_R = 0x31, // 原地右转（顺时针）180°
  CMD_WHEEL_FWD     = 0x32, // 直行微调前进，arg = mm（0 = 用 CFG.nudgeMm）
  CMD_WHEEL_BACK    = 0x33, // 直行微调后退，arg = mm（0 = 用 CFG.nudgeMm）
  CMD_WHEEL_STOP    = 0x34, // 中止调向并锁死轮电机
  CMD_PING      = 0x7F,   // Deadman 心跳
};

// ============================================================================
// 转向轮动作（V2.0）—— 「动作」是枚举，必须放这里：arduino 自动生成函数原型时
